public class function {

    static void greetUser() {
        System.out.println("Hello--World");
    }

    static void pattern() {
        for (int i = 0; i < 10; i++) {
            System.out.println("ayan");
        }
    }

    static void pattern2() {
        int i = 0;
        while (i < 10) {
            System.out.println("sheenam");
            i++;
        }
    }

    static void main(String[] args) {
        System.out.println();
        greetUser();
        System.out.println();
        pattern();
        System.out.println();
        pattern2();
    }


}
