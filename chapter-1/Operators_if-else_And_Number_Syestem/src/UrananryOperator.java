public class UrananryOperator {
    static void main(String[] args) {
        int x = 34;
        int y = -x;
        System.out.println(y);


        int a = 6;
        System.out.println(a);
        a= a+1;
        System.out.println(a);
        a += 1;
        System.out.println(a);
        a++;
        System.out.println(a);
        ++a;
        System.out.println(a);


        System.out.println(" value of p: ");
        int p = 6;
        System.out.println(p++);
        System.out.println(p);

        System.out.println(++p);
        System.out.println(p);

        System.out.println(p--);
        System.out.println(p);


        System.out.println(--p);
        System.out.println(p);




    }
}
