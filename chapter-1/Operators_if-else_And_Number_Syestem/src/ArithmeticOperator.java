public class ArithmeticOperator {
    static void main(String[] args) {
       int num1 = 20;
       int num2 = 7;

        System.out.println("the addition of two number: " + (num1+num2));
        System.out.println("the subtraction of two number: " + (num1-num2));
        System.out.println("the multiplication of two number: " + (num1*num2));
        System.out.println("the division of two number: " + (num1/num2));
        System.out.println("the division of two number: " + ((float)num1/num2));



        System.out.println("the addition of two number: " + (num1%num2));


        double num3 = 5;
        double num4 = 2;
        System.out.println("now move on double value");
        System.out.println("the addition of two number: " + (num3+num4));
        System.out.println("the subtraction of two number: " + (num3-num4));
        System.out.println("the multiplication of two number: " + (num3*num4));
        System.out.println("the division of two number: " + (num3/num4));

        System.out.println("the addition of two number: " + (num3%num4));

    }
}
